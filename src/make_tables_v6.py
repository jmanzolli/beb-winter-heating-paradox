def table_comp(runs, prov, div):
    hw = (prov or {}).get("hardware", {})
    sv = (prov or {}).get("solver", {})
    sel = [l for l in ("econ_lam0", "policy_lam100", "eps_0.00",
                       "det_meanT") if l in runs]
    rows = []
    for l in sel:
        r = runs[l]
        # rev. 2026-09-28: for lexicographic runs time_s/status belong to the
        # phase-2 (emissions) solve while obj/lb/gap are phase-1 values; the
        # runtime shown is now the total of both phases
        ph = r.get("phase2") or {}
        t_tot = r["time_s"] + ph.get("time_ph1", 0.0)
        t_txt = num(t_tot) if not ph else rev(num(t_tot))
        st_txt = str(r["status"]) + (rev(r"$^{\mathrm{a}}$") if ph else "")
        rows.append(f"R52 {l.replace(chr(95), chr(92) + chr(95))} & "
                    f"{num(r['obj'] / 1e3, 1)} & {num(r['lb'] / 1e3, 1)} & "
                    f"{num(r['abs_gap'])} & {r['rel_gap'] * 100:.3f} & "
                    f"{t_txt} & {st_txt} \\\\")
    for k, lbl in DIV_ORDER:
        rec = (div or {}).get("cases", {}).get(k)
        if not rec:
            continue
        g = rec.get("abs_gap", rec.get("worst_route_gap"))
        lbl = f"Div {DIV_SHORT.get(k, k)}"
        t, st = rec.get("time_s"), rec.get("status", "---")
        if "per_route" in rec:
            # fragmented case: fourteen independent solves; gap and runtime
            # aggregate as sums (rev. 2026-09-28, was worst route / blank)
            pr = rec["per_route"].values()
            g = rev(num(sum(v["abs_gap"] for v in pr)))
            t = rev(num(sum(v.get("time_s", 0.0) for v in pr)))
            st = rev("per route")
            lbl = rev(lbl) if lbl != f"Div {DIV_SHORT.get(k, k)[:8]}" else lbl
        else:
            g, t = num(g), num(t)
            if lbl != f"Div {DIV_SHORT.get(k, k)[:8]}":
                lbl = rev(lbl)
        rows.append(
            f"{lbl} & "
            f"{num(rec.get('differentiating_cost', 0) / 1e3, 1)} & --- & "
            f"{g} & --- & {t} & "
            f"{st} \\\\")
    body = r"""\begin{table*}[!t]
\caption{Computational performance and solve statistics.}
\label{tab:comp}
\centering
\scriptsize
\setlength{\tabcolsep}{4pt}
\begin{tabular}{@{}lrrrrrr@{}}
\toprule
\textbf{Instance} & \textbf{Incumbent} & \textbf{Bound} &
\textbf{Abs.\ gap} & \textbf{Rel.\ gap (\%%)} & \textbf{Runtime (s)} &
\textbf{Status} \\
\midrule
%s
\bottomrule
\end{tabular}
\par\smallskip
%s
\end{table*}
""" % ("\n".join(rows), rev(r"\parbox{\textwidth}{\footnotesize "
       r"$^{\mathrm{a}}$Lexicographic run: incumbent, bound and gaps certify "
       r"the phase-1 (cost) solve; runtime is the total of both phases and "
       r"the status refers to the phase-2 (emissions) solve. Division rows "
       r"report differentiating cost; the fragmented case sums its fourteen "
       r"per-route gaps and runtimes.}"))
    write("tab_comp.tex", body)


