def pick_representatives(runs, anchor="econ_lam0", endpoint="eps_0.00",
                         sep_tol=0.0, verbose=True):
    """Frontier points whose cost is certifiably above the previous one.

    Walking the frontier from the economic baseline towards a zero cap, a
    candidate B is admitted only when

        lb(B) > F1(A) + sep_tol,

    where A is the last admitted design. B's true cost is at least lb(B) and
    A's is at most F1(A), so the inequality certifies that B really is the
    costlier design and that the tabulated increment is a lower bound on the
    real one. Candidates whose bound overlaps the previous representative are
    skipped: their increment cannot be told apart from remaining search error,
    which is precisely the claim the table would otherwise be making.

    The anchor and the zero-cap endpoint are always kept -- the first is the
    reference every increment is measured from, the second is a defined policy
    point rather than a discovered one. Every other row has to earn its place.
    """
    # frontier order is by loosening cap, i.e. increasing cost
    cands = [l for l in FRONTIER_ORDER if l in runs and l != endpoint]
    if not cands:
        cands = [l for l in runs if l.startswith("eps_") and l != endpoint]
    cands.sort(key=lambda l: -(runs[l].get("eps") or 0.0))

    def structure(r):
        return (tuple(sorted(r.get("fleet", {}).items())),
                tuple(sorted(r.get("chargers", {}).items())),
                tuple(sorted((r.get("grid_kW") or {}).items())))

    kept, unseparated, samestruct = [], [], []
    last = runs.get(anchor)
    if last is None:
        return [l for l in ([anchor] + cands + [endpoint]) if l in runs]
    for l in cands:
        r = runs[l]
        lb, prev = r.get("lb"), last.get("F1")
        if lb is not None and prev is not None and lb <= prev + sep_tol:
            # cost bound overlaps the previous representative: the increment
            # cannot be distinguished from remaining search error
            unseparated.append((l, (prev - lb) / 1e3))
            continue
        if structure(r) == structure(last):
            # separated in cost but the same design; nothing new to show
            samestruct.append(l)
            continue
        kept.append(l)
        last = r
    out = [anchor] + kept + ([endpoint] if endpoint in runs else [])
    if verbose:
        print(f"representatives: {', '.join(out)}")
        if unseparated:
            print("  dropped, cost bound overlaps previous (kCAD): "
                  + ", ".join(f"{l} {ov:.1f}" for l, ov in unseparated))
        if samestruct:
            print("  dropped, same fleet/charger/grid configuration: "
                  + ", ".join(samestruct))
    return out


def table_designs(runs, labels=None):
    """Consolidated Route-52 experiment table: the designs that explain the
    frontier's transitions plus the deterministic and N-1 benchmarks, with
    out-of-sample reliability where it was evaluated (E8)."""
    env = os.environ.get("TAB_DESIGNS")
    if labels is None:
        labels = ([l for l in env.split(",") if l in runs] if env
                  else pick_representatives(runs) + ["det_meanT"])
    labels = [l for l in labels if l in runs]
    sel = [runs[l] for l in labels]
    if not sel:
        print("SKIP tab_designs: no frontier runs")
        return

    def cnt(r, pred):
        return sum(v for k, v in r["fleet"].items()
                   if pred(next(bc for bc in R.BUS_CLASSES if bc.name == k)))

    def fleet_of(r, at_depot):
        parts = []
        for key, v in sorted(r["chargers"].items()):
            n, p = key.split(":")
            if (n == "depot") is at_depot:
                parts.append(rf"{v}$\times${p}")
        return ", ".join(parts) if parts else "---"

    # out-of-sample floor compliance exists only for the designs the E8
    # harness evaluated: the lambda=100 design (composition identical to the
    # baseline) and the zero-emission endpoint
    rel = {}
    ra = load(os.environ.get("TAB_REL_BASE", "reliability_reserve10.json"))
    rz = load(os.environ.get("TAB_REL_ZERO", "reliability_zeroemission.json"))
    W = {w: R.SCEN[w][1] for w in ("mild", "cold", "verycold", "extreme", "severe")}  # v9: from the inputs
    def _floor(rr):
        # review (2026-11-06): days on which every trip is served with the
        # end-of-day reserve met (slack-only re-evaluation)
        lv = rr["levels"]["heat_cv_0.00"]
        return 100 * sum(lv[w]["p_all_trips_served"] * W[w] for w in W) / sum(W.values())
    if ra:
        rel["econ_lam0"] = _floor(ra)
    if rz:
        rel["eps_0.00"] = _floor(rz)

    # Column names describe the dominant structural feature of the SOLVED
    # first stage (advisor rule): designs emerge from the same stochastic
    # MILP under successively tighter caps and are labelled by what the
    # optimizer changed, not by an imposed configuration.
    # Names come from what the optimizer actually changed relative to the
    # previous column, not from the cap value: which structural move happens
    # at which cap differs between input revisions, and hardcoding it by eps
    # produced duplicate headers.
    def _ffh(r):
        return r.get("n_ffh", 0)

    def _ch(r):
        return tuple(sorted(r.get("chargers", {}).items()))

    def _grid(r):
        return tuple(sorted((r.get("grid_kW") or {}).items()))

    heads, det, prev, _nd = [], set(), None, 0
    for r in sel:
        lb = r["label"]
        if lb == "econ_lam0":
            name = (r"\textbf{Economic}", r"\textbf{baseline}")
        elif lb == "det_meanT":
            name = (r"\textbf{Mean-temp.}", r"\textbf{benchmark}" + rev(r"$^{\mathrm{b}}$"))
            det.add(lb)
        elif _ffh(r) == 0:
            name = (r"\textbf{Full heating}", r"\textbf{electrification}")
        elif prev is not None and _ffh(prev) - _ffh(r) >= 5:
            name = (r"\textbf{Mixed-fleet}", r"\textbf{transition}")
        elif (prev is not None and _ch(r) != _ch(prev)
              and [c for c in _ch(r) if c[0].startswith("depot")]
              == [c for c in _ch(prev) if c[0].startswith("depot")]):
            # depot unchanged, abatement bought with terminal charging (v9 D3)
            name = (r"\textbf{Terminal}", r"\textbf{charger upgrade}")
        elif prev is not None and (_ch(r) != _ch(prev)
                                   or _grid(r) != _grid(prev)):
            # most of the fleet stays; the abatement is bought with charging
            # capacity and grid headroom (or, at equal installed power, with
            # more plugs: v9 D1, 3x300 kW instead of 2x450 kW)
            def _dkw(x):
                return sum(int(k.split(":")[1]) * v for k, v in x.get("chargers", {}).items()
                           if k.startswith("depot"))
            if _dkw(r) > _dkw(prev) or _grid(r) != _grid(prev):
                name = (r"\textbf{Depot capacity}", r"\textbf{expansion}")
            else:
                name = (r"\textbf{Depot charger}", r"\textbf{reconfiguration}")
        else:
            name = (r"\textbf{Partial}", r"\textbf{electrification}")
        # intermediate designs always carry their remaining burner count: it
        # is what distinguishes them, and two caps can trigger the same move
        if lb not in ("econ_lam0", "det_meanT") and _ffh(r) > 0:
            name = name + (r"\textbf{(%d FFH)}" % _ffh(r),)
        if lb.startswith("lam_"):
            name = name[:-1] + (name[-1] + r"$^{\mathrm{c}}$",)
        # a short identifier so the prose can name a column without
        # restating its whole configuration
        if lb == "det_meanT":
            ident = "B"
        else:
            ident = f"D{_nd}"
            _nd += 1
        name = (r"\textbf{(%s)}" % ident,) + name
        heads.append(r"\makecell{%s}" % "\\\\".join(name))
        if lb != "det_meanT":
            prev = r

    def col(r, key, scale, dec, skip_det=False):
        if skip_det and r["label"] in det:
            return "---"
        return num(r[key] / scale, dec)

    rows = []
    for nm, pred in (
            ("Std.\\ battery, FFH-equipped (buses)",
             lambda b: b.ffh and b.batt_nom < 600),
            ("Std.\\ battery, electric-only",
             lambda b: not b.ffh and b.batt_nom < 600),
            ("Ext.\\ battery, FFH-equipped",
             lambda b: b.ffh and b.batt_nom > 600),
            ("Ext.\\ battery, electric-only",
             lambda b: not b.ffh and b.batt_nom > 600)):
        rows.append(f"{nm:<40} & " +
                    " & ".join(num(cnt(r, pred)) for r in sel) + r" \\")
    for nm, dep in (("Depot chargers (count$\\times$kW)", True),
                    ("Opportunity chargers", False)):
        rows.append(f"{nm:<40} & " +
                    " & ".join(fleet_of(r, dep) for r in sel) + r" \\")
    rows.append("Depot grid upgrade (kW)".ljust(40) + " & " +
                " & ".join(num(r.get("grid_kW", {}).get("depot", 0))
                           for r in sel) + r" \\")
    rows.append("Annual diesel (L)".ljust(40) + " & " +
                " & ".join(col(r, "diesel_L", 1, 0, skip_det=True)
                           for r in sel) + r" \\")
    def _cap(r):
        # the baseline is solved with a deliberately non-binding cap so that
        # the lexicographic phase 2 can run; that sentinel is not a policy
        # instrument and must not appear as one
        if (r["label"] in det or r.get("eps") is None
                or r["eps"] > 1e3):
            return "---"
        return num(r["eps"], 2)
    rows.append("Imposed cap $\\varepsilon^{\\mathrm{ann}}$ (t\\COtwo{}/yr)"
                .ljust(40) + " & " + " & ".join(_cap(r) for r in sel) + r" \\")
    rows.append("Achieved emissions (t\\COtwo{}/yr)".ljust(40) + " & " +
                " & ".join(col(r, "co2_t", 1, 2, skip_det=True)
                           for r in sel) + r" \\")
    rows.append("Annual cost, tabulated design (kCAD/yr)".ljust(40) + " & " +
                " & ".join(num(r["F1"] / 1e3, 1) for r in sel) + r" \\")
    base_f1 = runs["econ_lam0"]["F1"]
    rows.append("Increment, tabulated design (kCAD/yr)".ljust(40) + " & " +
                " & ".join(num((r["F1"] - base_f1) / 1e3, 1) for r in sel)
                + r" \\")
    # phase-1 cost-minimizing incumbent, so the certified minimum increment
    # and the tabulated (phase-2) increment are both explicit
    def _ph1(r):
        if r["label"] in det:
            return "---"
        if r.get("phase2"):
            return num((r["phase2"]["cost_incumbent_ph1"] - base_f1) / 1e3, 1)
        return num((r["F1"] - base_f1) / 1e3, 1)
    # review (2026-11-06): the certification rule fixes the ORDER of the
    # designs, not the size of their increments; report the interval that the
    # bounds allow, [lb_i - F1_0, F1_i - lb_0]
    lb0 = runs["econ_lam0"].get("lb", base_f1)
    def _ivl(r):
        if r["label"] in det or r["label"] == "econ_lam0":
            return "---"
        # a price solution bounds the objective F1 + lam*E; any design with
        # emissions <= E* then costs at least lb - lam*E*
        lbF = r.get("lb", r["F1"]) - (r.get("lam") or 0.0) * r["co2_t"]
        lo = (lbF - base_f1) / 1e3
        hi = (r["F1"] - lb0) / 1e3
        return f"{lo:.1f}--{hi:.1f}"
    rows.append(("Increment, certified range (kCAD/yr)" + rev(r"$^{\mathrm{a}}$")).ljust(40) + " & " +
                " & ".join(_ivl(r) for r in sel) + r" \\")
    rows.append("Feasible on full scenario set".ljust(40) + " & " +
                " & ".join("no" if r["label"] in det else "yes"
                           for r in sel) + r" \\")
    rows.append("Winter days fully served (\\%)".ljust(40) + " & " +
                " & ".join(num(rel.get(r["label"]), 2) for r in sel) + r" \\")
    rows.append("Absolute optimality gap (kCAD/yr)".ljust(40) + " & " +
                " & ".join(num(r["abs_gap"] / 1e3, 2) for r in sel) + r" \\")
    # visual separator (extra space) before the mean-temperature benchmark
    # column: it is not on the stochastic emissions-reduction pathway
    ncol = len(sel)
    if det:
        colspec = "r" * (ncol - 1) + r"@{\hskip 14pt}r"
    else:
        colspec = "r" * ncol
    # table notes (rev. 2026-09-28): what the phase-1 row measures and what
    # the benchmark column's cost is, both read from the archives
    dm = runs.get("det_meanT", {})
    t_mean = (dm.get("scen_ops", {}).get("winteravg", {}) or {}).get("T")
    theta = runs["econ_lam0"].get("phase2", {}).get("lex_tol", 500.0) / 1e3
    note_a = (r"$^{\mathrm{a}}$From the solver lower bounds of this design "
              r"and of (D0); the lexicographic emissions pass (Sec.~II-D) may "
              r"add up to $\theta=%.1f$~kCAD/yr to the tabulated cost." % theta)
    note_b = ""
    if t_mean is not None:
        note_b = (r" $^{\mathrm{b}}$Optimized on one mean winter day "
                  r"($%.1f^\circ$C) plus the off-season day; not operable on "
                  r"the full scenario set, so diesel and emissions are omitted "
                  r"(full-set re-evaluation: Sec.~IV-C)." % t_mean)
    note_c = ""
    for r in sel:
        if (r.get("lam") or 0) > 0 and r["label"].startswith("lam_"):
            note_c += (r" $^{\mathrm{c}}$Solution at a carbon price of "
                       r"%s~CAD/t\COtwo{}, which dominates the solution of the "
                       r"nearest cap." % f"{r['lam']:,.0f}".replace(",", "{,}"))
    notes = rev(r"\parbox{\textwidth}{\footnotesize " + note_a + note_b + note_c + "}")
    body = r"""\begin{table*}[!t]
\caption{Representative Route~52 designs and mean-temperature benchmark.}
\label{tab:designs}
\centering
\footnotesize
\setlength{\tabcolsep}{5.5pt}
\renewcommand{\arraystretch}{1.0}
\begin{tabular}{@{}l%s@{}}
\toprule
\textbf{Design or outcome} & %s \\
\midrule
%s
\bottomrule
\end{tabular}
\par\smallskip
%s
\end{table*}
""" % (colspec, " & ".join(heads), "\n".join(rows), notes)
    write("tab_designs.tex", body)


