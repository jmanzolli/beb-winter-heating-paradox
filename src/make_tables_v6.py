# per-scenario operating record of the ECONOMIC BASELINE, so the supplement
# table and the manuscript's weather-adaptive-operation figure describe the
# same run (advisor consistency requirement)
def table_scen(runs, label="econ_lam0"):
    r = runs.get(label)
    if not r or "scen_ops" not in r:
        print(f"SKIP tab_scen: {label} has no scen_ops "
              f"(record predates the campaign_v5.py change); re-solve it or "
              f"pick a label that has it")
        return
    rows = []
    for w in R.SCEN:
        s = r["scen_ops"][w]
        tot = s["q_el_kWh"] + s["q_ffh_kWh"]
        share = 100.0 * s["q_ffh_kWh"] / tot if tot > 1e-9 else 0.0
        dsl_cost = R.DIESEL_PRICE * s["diesel_L"]
        rows.append(
            f"{BAND_LABEL.get(w, w):<10} & {s['T']:>6.1f} & {s['days']:>3d} & "
            f"{num(s['q_el_kWh'])} & {num(s['q_ffh_kWh'])} & {share:.0f} & "
            f"{num(s['diesel_L'])} & {num(s['precond_kWh'])} & "
            f"{num(s['electricity_cost'])} & {num(dsl_cost)} & "
            f"{num(s['electricity_cost'] + dsl_cost)} \\\\")
    body = r"""\begin{table*}[!t]
\caption{Scenario operation of the economic baseline design, per
representative day.}
\label{tab:scen}
\centering
\footnotesize
\setlength{\tabcolsep}{4pt}
\renewcommand{\arraystretch}{1.12}
\begin{tabular}{@{}lrrrrrrrrrr@{}}
\toprule
\textbf{Band} &
\textbf{$T_\omega$ ($^\circ$C)} &
\textbf{\makecell{Weight\\(d/yr)}} &
\textbf{\makecell{Electric heat\\(kWh/d)}} &
\textbf{\makecell{FFH heat\\(kWh/d)}} &
\textbf{\makecell{FFH share\\(\%%)}} &
\textbf{\makecell{Diesel\\(L/d)}} &
\textbf{\makecell{Precond.\\(kWh/d)}} &
\textbf{\makecell{Electricity\\(CAD/d)}} &
\textbf{\makecell{Diesel cost\\(CAD/d)}} &
\textbf{\makecell{Total variable\\energy (CAD/d)}} \\
\midrule
%s
\bottomrule
\end{tabular}
\end{table*}
""" % ("\n".join(rows),)
    write("tab_scen.tex", body)


