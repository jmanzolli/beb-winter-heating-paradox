def load(fn):
    return json.load(open(fn)) if os.path.exists(fn) else None


def num(x, d=0):
    """Thousands-separated fixed-decimal, or an em dash for missing data."""
    if x is None:
        return "---"
    return f"{x:,.{d}f}"


def rev(s):
    """Mark a revised cell or phrase in red (\\rev is defined in both preambles).
    Revision 2026-09-28: every value or label changed after the v8 submission
    draft goes through this, so the manuscript shows the change."""
    if os.environ.get("TAB_NO_REV"):
        return s
    return r"\rev{%s}" % s


def write(name, body):
    stamp = ("% GENERATED by make_tables_v6.py from campaign result files.\n"
             "% Do not edit by hand - regenerate instead.\n")
    for d in [OUTDIR] + TEXDIRS:
        open(os.path.join(d, name), "w").write(stamp + body)
    print("wrote", name)


