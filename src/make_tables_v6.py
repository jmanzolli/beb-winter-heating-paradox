"""
Generate every manuscript table from the v6 result files (protocol Section 6,
item 'Generate all final manuscript tables programmatically from model
outputs. Avoid manual transcription.').

Emits LaTeX fragments into tables_v6/ :

  tab_scen.tex      scenario operation of the carbon-price design (Table IV)
  tab_designs.tex   frontier designs and certified bounds       (Table V)
  tab_division.tex  fragmented vs coordinated division cases
  tab_stability.tex near-optimal equipment ranges
  tab_comp.tex      computational performance

Every number is read from campaign_v5_results.json / campaign_division_v5.json
/ provenance_v5.json. Nothing is typed in.

Table IV's cost column is split rather than left as the ambiguous "Energy
cost" of earlier drafts: electricity and diesel are reported separately and
their sum is labelled total variable energy cost. Capital, demand charges and
FFH O&M are NOT in it -- those are annual, not per representative day, and
folding them in was what made the old column unreadable.

Usage: ROUTE_INPUTS=route52_inputs_v5.json python3 make_tables_v6.py
"""

import json
import os

os.environ.setdefault("ROUTE_INPUTS", "route52_inputs_v5.json")
import route52_prototype as R

# Written to the code tree (archive) and straight into the manuscript tree,
# so main.tex picks the tables up with \input and no file is ever copied by
# hand -- that hand copy is exactly where stale numbers used to creep in.
OUTDIR = "tables_v6"
os.makedirs(OUTDIR, exist_ok=True)
# both manuscript trees: long draft (../Overleaf) and submission master
# (../Overleaf/short) each \input their own tables_v6/
# submission master only; the long draft at ../Overleaf is a frozen archive
TEXDIRS = []
for base in (os.path.join("..", "Overleaf", "short"),):
    if os.path.isdir(base):
        d = os.path.join(base, "tables_v6")
        os.makedirs(d, exist_ok=True)
        TEXDIRS.append(d)
RES = os.environ.get("TAB_RES", "campaign_v5_results.json")
DIV = os.environ.get("TAB_DIV", "campaign_division_v5.json")
PROV = os.environ.get("TAB_PROV", "provenance_v5.json")

BAND_LABEL = {"mild": "Mild", "cold": "Cold", "verycold": "Very cold",
              "extreme": "Extreme", "severe": "Severe",
              "offseason": "Off-season"}


def load(fn):
    return json.load(open(fn)) if os.path.exists(fn) else None


def num(x, d=0):
    """Thousands-separated fixed-decimal, or an em dash for missing data."""
    if x is None:
        return "---"
    return f"{x:,.{d}f}"


def write(name, body):
    stamp = ("% GENERATED by make_tables_v6.py from campaign result files.\n"
             "% Do not edit by hand - regenerate instead.\n")
    for d in [OUTDIR] + TEXDIRS:
        open(os.path.join(d, name), "w").write(stamp + body)
    print("wrote", name)


