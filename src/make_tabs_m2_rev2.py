"""Tables of main_2.tex changed in the revision of 2026-11 (review of 2026-11-09).

  tab_division_m2   four division plans (route by route, shared chargers,
                    shared bus pool, full coordination), from the v9rev archive
                    and the v10 solves; common lower bound of the joint plans
  tab_designs_m2    the table written by make_tables_v6.py, with plain design
                    labels, the design-day design added as a column, and the
                    old out-of-sample row removed

No solver. Run from code/: python3 make_tabs_m2_rev2.py
(run after make_tables_v6.py if that script is run again).
"""
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "overleaf-git", "tables_v6")
D = json.load(open(os.path.join(HERE, "v9rev", "campaign_division_v9rev.json")))["cases"]
A, C, Dv = D["A_fragmented"], D["C_shared_infra_frozen_z"], D["D_full_coordination"]
B = json.load(open(os.path.join(HERE, "v10rev", "div10_B.json")))["cases"][
    "B_shared_infra_route_locked"]
Dn = json.load(open(os.path.join(HERE, "v10rev", "div10_D.json")))["cases"][
    "D_full_coordination"]
lb_joint = (Dn["differentiating_cost"] - Dn["abs_gap"]) / 1e3
a_lb, a_inc = A["lb_sum"] / 1e3, A["differentiating_cost"] / 1e3
plans = [("Route by route", A, a_lb), ("Shared chargers", B, lb_joint),
         ("Shared bus pool", C, lb_joint), ("Full coordination", Dv, lb_joint)]


def row(name, f):
    return name + " & " + " & ".join(f(n, c, lb) for n, c, lb in plans) + r" \\"


def sav(n, c, lb):
    if c is A:
        return "ref."
    s = a_inc - c["differentiating_cost"] / 1e3
    return f"{s:.1f} ({100 * s / a_inc:.1f}\\%)"


L = [r"% GENERATED by make_tabs_m2_rev2.py from the division archives. Do not edit by hand.",
     r"\begin{table*}[pos=tp]",
     r"\caption{Four plans for the Arrow Road division (183 buses, 14 routes). Costs exclude "
     r"the bus capital common to all plans. The three joint plans share one lower bound, "
     r"because their solutions are feasible under full coordination. Savings are between best solutions, relative "
     r"to the route-by-route plan.}",
     r"\label{tab:garage}", r"\centering", r"\small", r"\setlength{\tabcolsep}{6pt}",
     r"\fittab{@{}lrrrr@{}}{", r"\toprule",
     r"\textbf{Quantity} & " + " & ".join(r"\makecell{\textbf{%s}}" % n.replace(" ", r"}\\\textbf{", 1)
                                         if n != "Route by route" else r"\makecell{\textbf{Route}\\\textbf{by route}}"
                                         for n, _, _ in plans) + r" \\", r"\midrule",
     row("Best solution (kCAD/yr)", lambda n, c, lb: f"{c['differentiating_cost'] / 1e3:,.1f}"),
     row("Lower bound (kCAD/yr)", lambda n, c, lb: f"{lb:,.1f}"),
     row("Saving, best solutions (kCAD/yr)", sav),
     row("Heater-equipped buses", lambda n, c, lb: f"{c['n_ffh']}"),
     row("Share of fleet (\\%)", lambda n, c, lb: f"{100 * c['n_ffh'] / 183:.0f}"),
     row("Terminal chargers", lambda n, c, lb: f"{c['n_opp_chargers']}"),
     row("Diesel (kL/yr)", lambda n, c, lb: f"{c['diesel_L'] / 1e3:.1f}"),
     row("Onboard emissions (t\\COtwo{}/yr)", lambda n, c, lb: f"{c['co2_t']:.1f}"),
     r"\bottomrule", "}", r"\par\smallskip",
     r"\parbox{\linewidth}{\small Certified saving of joint planning: at least "
     f"{a_lb - C['differentiating_cost'] / 1e3:.1f}~kCAD/yr, the route-by-route lower bound "
     r"minus the best joint solution; at most "
     f"{a_inc - lb_joint:.1f}~kCAD/yr.}}",
     r"\end{table*}"]
open(os.path.join(OUT, "tab_division_m2.tex"), "w").write("\n".join(L) + "\n")

# ---- designs table: add the design-day column
ev = {r["label"]: r for f in ("rev10_ddeval.json", "rev10_d0eval.json")
      for r in json.load(open(os.path.join(HERE, "v10rev", f)))["runs"]}
dd, d0 = ev["det_designday_eval"], ev["econ_lam0_eval"]
fl = dd["fleet"]
add = {"Std.\\ battery, FFH-equipped": str(fl.get("NF-std-FFH", 0)),
       "Std.\\ battery, electric-only": str(fl.get("NF-std-eOnly", 0)),
       "Ext.\\ battery, FFH-equipped": str(fl.get("NF-ext-FFH", 0)),
       "Ext.\\ battery, electric-only": str(fl.get("NF-ext-eOnly", 0)),
       "Depot chargers": r"3$\times$300", "Opportunity chargers": r"1$\times$300",
       "Depot grid upgrade": f"{dd['grid_kW']['depot']:.0f}",
       "Annual diesel": f"{dd['diesel_L']:,.0f}", "Imposed cap": "---",
       "Achieved emissions": f"{dd['co2_t']:.2f}",
       "Annual cost, tabulated": f"{dd['F1'] / 1e3:,.1f}",
       "Increment, tabulated": f"{(dd['F1'] - d0['F1']) / 1e3:.1f}",
       "Increment, certified": "---", "Feasible on full": "yes",
       "Absolute optimality gap": f"{dd['abs_gap'] / 1e3:.2f}"}
p = os.path.join(OUT, "tab_designs_m2.tex")
s = open(p).read()
if "Design-day" not in s:
    out = []
    for ln in s.split("\n"):
        if ln.startswith("Winter days fully served"):
            continue
        if ln.startswith(r"\fittab{"):
            ln = ln.replace(r"lrrrrr@{\hskip 14pt}r@{}", r"lrrrrr@{\hskip 14pt}rr@{}")
        if ln.startswith(r"\textbf{Design or outcome}"):
            ln = ln.rstrip().rstrip("\\").rstrip() + \
                r" & \makecell{\textbf{Design-day}\\\textbf{benchmark}$^{\mathrm{d}}$} \\"
            for k in range(5):
                ln = ln.replace(r"\textbf{(D%d)}" % k, r"\textbf{D%d}" % k)
            ln = ln.replace(r"\textbf{(B)}", r"\textbf{B}").replace(
                r"\textbf{Full heating}\\\textbf{electrification}", r"\textbf{Heater-free}")
        for key, val in add.items():
            if ln.startswith(key):
                ln = ln.rstrip().rstrip("\\").rstrip() + f" & {val} \\\\"
        out.append(ln)
    s = "\n".join(out)
    s = s.replace("and mean-temperature benchmark.}", "and the two single-day benchmarks.}")
    s = s.replace("Opportunity chargers ", "Terminal chargers    ")
    s = s.replace("Std.\\ battery, FFH-equipped (buses)", "Standard battery, heater (buses)   ")
    s = s.replace("Std.\\ battery, electric-only", "Standard battery, electric-only")
    s = s.replace("Ext.\\ battery, FFH-equipped", "Extended battery, heater")
    s = s.replace("Ext.\\ battery, electric-only", "Extended battery, electric-only")
    s = s.replace(r"\textbf{(18 FFH)}", r"\textbf{(18 heaters)}").replace(
        r"\textbf{(6 FFH)}", r"\textbf{(6 heaters)}").replace(
        r"\textbf{(4 FFH)}", r"\textbf{(4 heaters)}")
    s = s.replace("of this design and of (D0);", "of this design and of design D0;")
    s = s.replace(r"nearest cap.}", r"nearest cap. $^{\mathrm{d}}$Sized for the severe band alone and "
                  r"evaluated on the full scenario set with its first stage fixed; the increment is "
                  r"relative to design D0 evaluated by the same procedure "
                  f"({d0['F1'] / 1e3:,.1f}~kCAD/yr, {d0['co2_t']:.1f}~t\\COtwo{{}}).}}")
    open(p, "w").write(s)
print(open(os.path.join(OUT, "tab_division_m2.tex")).read())
print(open(p).read()[300:2600])
