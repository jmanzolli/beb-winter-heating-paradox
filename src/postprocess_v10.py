"""Post-processing of the review runs of 2026-11-09/10 (run_review_v10.sh).

Reads the result shards in v10rev/ and the v9rev archives in server_v10/, and
writes v10rev/RESULTS_v10.md and v10rev/results_v10.json with
  1. heater-capital runs (M1): incumbents, bounds, and the switch prices on the
     lower envelope of every known lambda = 0 design
  2. fixed-design evaluations (M8)
  3. reliability protocol v10 (M2-M4, M3, M8): per band and per winter
  4. division comparison (M7): nested bounds, cost-part differences, and the
     fragmented case re-billed on one connection with linear grid pricing

No solver. Usage: python3 postprocess_v10.py
"""
import glob
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
V10 = os.path.join(HERE, "v10rev")
ARC = os.path.join(HERE, "server_v10")
CRF_BUS, CRF_GRID, GRID_PER_KW, DEPOT_EXISTING = 0.1128, 0.0802, 200.0, 600.0
BANDS = ["mild", "cold", "verycold", "extreme", "severe"]
DESIGNS = [("econ_lam0", "D0 (18 heaters)"), ("eps_0.00", "D4 (electric-only)"),
           ("relmatch_eps0_r25", "Electric-only, 25 kWh reserve"),
           ("relmatch_eps0_r100", "Electric-only, 100 kWh reserve, planned assignment"),
           ("relmatch_eps0_r100#h", "Electric-only, 100 kWh reserve, hedged assignment"),
           ("det_designday", "Design-day (3 heaters), planned assignment"),
           ("det_designday#h", "Design-day (3 heaters), hedged assignment")]
LEVELS = [("trac_fixT", "traction only, fixed temperature"),
          ("trac", "traction + sampled temperature"),
          ("data", "+ data-implied heat variation"),
          ("cv0.20", "+ 20% heat variation (stress)")]
out = {}
md = ["# Review runs v10: results", "",
      "Generated by `postprocess_v10.py` from `v10rev/`. Costs in kCAD/yr unless noted.", ""]


def k(v, nd=1):
    return f"{v / 1e3:,.{nd}f}"


# ------------------------------------------------------------------ 1. capex
arc = {r["label"]: r for r in json.load(open(os.path.join(
    ARC, "campaign_v9rev_results.json")))["runs"]}
runs = {}
for f in sorted(glob.glob(os.path.join(V10, "rev10_*.json"))):
    for r in json.load(open(f))["runs"]:
        runs[r["label"]] = r
md += ["## 1. Heater installed capital (M1)", "",
       "| Heater price (kCAD) | Cost | Lower bound | Gap | Heaters | CO2 (t) | Chargers |",
       "|---|---|---|---|---|---|---|"]
cap = {}
for lbl, r in sorted(runs.items()):
    if not lbl.startswith("ffh_capex_l0_"):
        continue
    fc = int(lbl.rsplit("_", 1)[1])
    cap[fc] = r
    md.append(f"| {fc / 1e3:g} | {k(r['F1'])} | {k(r['lb'])} | {k(r['abs_gap'])} | "
              f"{r['n_ffh']} | {r['co2_t']:.1f} | {r['chargers']} |")
# every known lambda = 0 design, stripped of heater capital: cost(c) = F0 + n*CRF*c
cands = []
for lbl, r in arc.items():
    if r.get("lam") == 0.0 and "F1" in r and r.get("n_ffh") is not None \
            and (lbl == "econ_lam0" or lbl.startswith("eps_")):
        cands.append((lbl, r["F1"], r["n_ffh"]))
for fc, r in cap.items():
    cands.append((f"capex_{fc}", r["F1"] - r["n_ffh"] * fc * CRF_BUS, r["n_ffh"]))
cands.append(("det_designday_eval", runs["det_designday_eval"]["F1"],
              runs["det_designday_eval"]["n_ffh"]))
best = {}
for lbl, f0, n in cands:
    if n not in best or f0 < best[n][1]:
        best[n] = (lbl, f0)
md += ["", "Cheapest known design per heater count, heater capital removed "
       "(cost at price c = F0 + n x 0.1128 x c):", "",
       "| Heaters | F0 | Source run |", "|---|---|---|"]
for n in sorted(best, reverse=True):
    md.append(f"| {n} | {k(best[n][1], 2)} | {best[n][0]} |")
# lower envelope switch prices
grid = [c * 10.0 for c in range(0, 12001)]          # CAD, 0..120 kCAD
env, prev = [], None
for c in grid:
    n = min(best, key=lambda n: best[n][1] + n * CRF_BUS * c)
    if n != prev:
        env.append((c, n))
        prev = n
md += ["", "Lower envelope of known designs (switch prices):", ""]
for (c0, n), nxt in zip(env, env[1:] + [(None, None)]):
    hi = f"{nxt[0] / 1e3:.1f}" if nxt[0] is not None else "above"
    md.append(f"- {n} heaters cheapest from {c0 / 1e3:.1f} to {hi} kCAD per heater")
d4_lb = arc["eps_0.00"]["lb"]
n_last = env[-2][1] if len(env) > 1 else None
if n_last:
    c_lb = (d4_lb - best[n_last][1]) / (n_last * CRF_BUS)
    md.append(f"- with the D4 lower bound ({k(d4_lb)}) instead of its incumbent, "
              f"full removal is not cheapest below {c_lb / 1e3:.1f} kCAD per heater")
md += ["", "Notes: all five solves stopped at the 2 h limit, gaps 2.4-6.8 kCAD "
       "(target 1). The envelope uses incumbents, so each switch price is "
       "'best known', not certified. Designs with 3-6 heaters come from "
       "CO2-capped or design-day runs, not from cost minimisation at these "
       "prices; a cheaper low-heater design would raise the full-removal price.", ""]
out["capex"] = {"runs": {fc: {x: r[x] for x in ("F1", "lb", "abs_gap", "n_ffh", "co2_t",
                                                  "chargers")} for fc, r in cap.items()},
                "best_by_heaters": {n: {"label": v[0], "F0": v[1]} for n, v in best.items()},
                "envelope": env}

# ------------------------------------------------------------------ 2. evals
md += ["## 2. Fixed-design evaluation on the full scenario set (M8)", "",
       "| Design | Cost | Gap (CAD) | Heaters | CO2 (t) | Chargers |", "|---|---|---|---|---|---|"]
for lbl in ("econ_lam0_eval", "det_designday_eval"):
    r = runs[lbl]
    md.append(f"| {lbl} | {k(r['F1'])} | {r['abs_gap']:.0f} | {r['n_ffh']} | "
              f"{r['co2_t']:.1f} | {r['chargers']} |")
dd, d0 = runs["det_designday_eval"], runs["econ_lam0_eval"]
md += ["", f"Design-day minus D0: {k(dd['F1'] - d0['F1'])} kCAD/yr "
       f"({100 * (dd['F1'] / d0['F1'] - 1):.2f}%), CO2 {dd['co2_t'] - d0['co2_t']:+.1f} t. "
       f"D4 (archive): {k(arc['eps_0.00']['F1'])}.", ""]
out["evals"] = {l: {x: runs[l][x] for x in ("F1", "abs_gap", "n_ffh", "co2_t")}
                for l in ("econ_lam0_eval", "det_designday_eval")}

# ------------------------------------------------------------- 3. reliability
rel, hedge = {}, {}
for d, _ in DESIGNS:
    for lv, _ in LEVELS:
        # "<design>#h": hedged day-ahead assignment (run_hedged_v10.sh)
        fn = os.path.join(V10, f"rel_v10h_{d[:-2]}_{lv}.json" if d.endswith("#h")
                          else f"rel_v10_{d}_{lv}.json")
        if os.path.exists(fn):
            j = json.load(open(fn))
            rel[d, lv] = j["levels"].get(lv, {})
            if d.endswith("#h"):
                hedge[d] = j["assignment"]["bands"]
md += ["## 3. Reliability protocol v10 (M2-M4, M3, M8)", "",
       "1,000 draws per band, common random numbers across designs. "
       "Cells: reserve-compliant / trips completed / comfort met, % of days. "
       "'...' = band not finished.", ""]
out["reliability"] = {}
for lv, lvname in LEVELS:
    md += [f"### {lvname} (`{lv}`)", "",
           "| Design | " + " | ".join(BANDS) + " |", "|---|" + "---|" * len(BANDS)]
    for d, dname in DESIGNS:
        if (d, lv) not in rel:
            continue
        cells = []
        for b in BANDS:
            s = rel[d, lv].get(b)
            cells.append("..." if not s else
                         f"{100 * s['p_reserve_compliant']:.1f} / "
                         f"{100 * s['p_trips_completed']:.1f} / "
                         f"{100 * s['p_comfort_met']:.1f}")
        md.append(f"| {dname} | " + " | ".join(cells) + " |")
        out["reliability"][f"{d}|{lv}"] = rel[d, lv]
    md.append("")
md += ["### Winter totals", "",
       "Per winter (151 days, 276 trips/day): days below reserve, days with a "
       "lost trip, trips lost; worst of the 24 historical winters in brackets.", "",
       "| Design | Level | Reserve-compliant days % | Trips-completed days % | "
       "Comfort days % | Breach days/winter (worst) | Trip-loss days/winter (worst) | "
       "Trips lost/winter (worst) |", "|---|---|---|---|---|---|---|---|"]
for d, dname in DESIGNS:
    for lv, _ in LEVELS:
        ww = rel.get((d, lv), {}).get("winter_weighted")
        if not ww:
            if (d, lv) in rel:
                md.append(f"| {dname} | {lv} | ... | ... | ... | ... | ... | ... |")
            continue
        h = ww["historical_24_winters"]
        md.append(
            f"| {dname} | {lv} | {100 * ww['p_day_reserve_compliant']:.2f} | "
            f"{100 * ww['p_day_trips_completed']:.3f} | {100 * ww['p_day_comfort_met']:.2f} | "
            f"{ww['reserve_breach_days_per_winter']:.2f} ({h['reserve_breach_days']['max']:.2f}, "
            f"{h['reserve_breach_days']['worst_winter']}) | "
            f"{ww['trip_loss_days_per_winter']:.2f} ({h['trip_loss_days']['max']:.2f}) | "
            f"{ww['trips_lost_per_winter']:.2f} ({h['trips_lost']['max']:.2f}) |")
md.append("")
md += ["### Severe band detail", "",
       "| Design | Level | Reserve % | Trips % | Comfort % | Trips lost/day | "
       "Shortfall given fail (kWh) | Heat shortfall (kWh/day) |", "|---|---|---|---|---|---|---|---|"]
for d, dname in DESIGNS:
    for lv, _ in LEVELS:
        s = rel.get((d, lv), {}).get("severe")
        if s:
            md.append(f"| {dname} | {lv} | {100 * s['p_reserve_compliant']:.1f} | "
                      f"{100 * s['p_trips_completed']:.1f} | {100 * s['p_comfort_met']:.1f} | "
                      f"{s['mean_trips_lost']:.3f} | {s['shortfall_given_fail_mean_kWh']:.0f} | "
                      f"{s['mean_heat_short_kWh_day']:.2f} |")
md.append("")
if hedge:
    md += ["### Hedged day-ahead assignment", "",
           "Per band, the assignment that tolerates the largest uniform rise in "
           "traction energy on a cold day of the band (10th percentile of its daily "
           "means). Cells: tolerated multiplier (day temperature, C).", "",
           "| Design | " + " | ".join(BANDS) + " |", "|---|" + "---|" * len(BANDS)]
    for d, dname in DESIGNS:
        if d in hedge:
            md.append(f"| {dname} | " + " | ".join(
                f"{hedge[d][b]['kappa_tolerated']} ({hedge[d][b]['T']})" for b in BANDS) + " |")
    md.append("")
    out["hedged_assignment"] = hedge

# --------------------------------------------------------------- 4. division
div = json.load(open(os.path.join(ARC, "campaign_division_v9rev.json")))["cases"]
A, C, D9 = div["A_fragmented"], div["C_shared_infra_frozen_z"], div["D_full_coordination"]
B = json.load(open(os.path.join(V10, "div10_B.json")))["cases"]["B_shared_infra_route_locked"]
D = json.load(open(os.path.join(V10, "div10_D.json")))["cases"]["D_full_coordination"]
a_parts = {}
for v in A["per_route"].values():
    for kk, x in v["cost_parts"].items():
        a_parts[kk] = a_parts.get(kk, 0.0) + x
a_ub, a_lb = A["differentiating_cost"], A["lb_sum"]
coord_ub = min(C["obj_solver"], B["obj_solver"], D["obj_solver"], D9["obj_solver"])
coord_lb = max(D["lb_solver"], D9["lb_solver"])     # D relaxes B and C
md += ["## 4. Division comparison (M7)", "",
       "| Case | Incumbent | Lower bound | Heaters | Depot peak (kW) | CO2 (t) | Source |",
       "|---|---|---|---|---|---|---|",
       f"| A fragmented (sum of 14 routes) | {k(a_ub)} | {k(a_lb)} | {A['n_ffh']} | "
       f"{A['sum_route_depot_peaks_kW']:.0f} | {A['co2_t']:.0f} | v9rev |",
       f"| B route-locked, shared infrastructure | {k(B['obj_solver'])} | {k(B['lb_solver'])} | "
       f"{B['n_ffh']} | {B['peak_depot_kW']:.0f} | {B['co2_t']:.0f} | v10 |",
       f"| C shared pool, frozen assignment | {k(C['obj_solver'])} | {k(C['lb_solver'])} | "
       f"{C['n_ffh']} | {C['peak_depot_kW']:.0f} | {C['co2_t']:.0f} | v9rev |",
       f"| D full coordination | {k(D9['obj_solver'])} | {k(D9['lb_solver'])} | "
       f"{D9['n_ffh']} | {D9['peak_depot_kW']:.0f} | {D9['co2_t']:.0f} | v9rev |",
       f"| D full coordination (re-run) | {k(D['obj_solver'])} | {k(D['lb_solver'])} | "
       f"{D['n_ffh']} | {D['peak_depot_kW']:.0f} | {D['co2_t']:.0f} | v10 |", "",
       "Nesting: every C solution is feasible for B (a frozen assignment fixes "
       "per-route class counts), and every B solution is feasible for D. So "
       "opt(D) <= opt(B) <= opt(C), and D's lower bound holds for all three.", "",
       f"- All three coordinated optima lie in [{k(coord_lb)}, {k(coord_ub)}] "
       f"(width {k(coord_ub - coord_lb)}, {100 * (coord_ub - coord_lb) / coord_ub:.1f}%).",
       f"- Fragmented optimum lies in [{k(a_lb)}, {k(a_ub)}].",
       f"- Saving of coordination vs fragmented: certified at least "
       f"{k(a_lb - coord_ub)} ({100 * (a_lb - coord_ub) / a_lb:.1f}%), "
       f"incumbent-to-incumbent {k(a_ub - coord_ub)} ({100 * (a_ub - coord_ub) / a_ub:.1f}%), "
       f"at most {k(a_ub - coord_lb)} ({100 * (a_ub - coord_lb) / a_ub:.1f}%).",
       f"- Route-locked incumbent alone already saves {k(a_ub - B['obj_solver'])} "
       f"({100 * (a_ub - B['obj_solver']) / a_ub:.1f}%) against fragmented.",
       f"- Value of pooling the fleet across routes (B to D): at most "
       f"{k(min(B['obj_solver'], coord_ub) - coord_lb)}, not resolved by the bounds.",
       "- The v10 MIP start passed first-stage variables only; Gurobi did not "
       "complete it to the C objective, so the B and D re-runs ended above C. "
       "Their lower bounds are valid and D's improved.", ""]
md += ["Cost parts (kCAD/yr):", "",
       "| Part | A | B | C | B - A | C - A |", "|---|---|---|---|---|---|"]
for part in ("charger_site_capital", "grid_capital", "demand_charges", "electricity",
             "ffh_om", "diesel_cost"):
    a, b, c = a_parts[part], B["cost_parts"][part], C["cost_parts"][part]
    md.append(f"| {part} | {k(a)} | {k(b)} | {k(c)} | {k(b - a)} | {k(c - a)} |")
md.append(f"| total | {k(a_ub)} | {k(B['obj_solver'])} | {k(C['obj_solver'])} | "
          f"{k(B['obj_solver'] - a_ub)} | {k(C['obj_solver'] - a_ub)} |")
# linear grid pricing on one shared depot connection
cb = A["common_basis"]
lin = CRF_GRID * GRID_PER_KW
a_lin_grid = lin * max(0.0, cb["coincident_peak_kW"]["win"] - DEPOT_EXISTING)
a_shared_lin = a_ub - cb["separate_depot_grid_cost"] + a_lin_grid \
    + (cb["shared_depot_demand_cost"] - cb["separate_depot_demand_cost"])
a_lb_shared_lin = a_lb - cb["separate_depot_grid_cost"] + a_lin_grid


def depot_lin(rec):
    return (rec["obj_solver"] - CRF_GRID * GRID_PER_KW * rec["grid_kW"].get("depot", 0.0)
            + lin * max(0.0, rec["peak_depot_kW"] - DEPOT_EXISTING))


md += ["", "Fragmented designs on one shared depot connection (designs and dispatch "
       "fixed; depot grid upgrade re-priced):", "",
       f"- as planned, 14 separate connections each with the existing 600 kW: {k(a_ub)}",
       f"- one connection, tiered grid (8 MW tier; archive): {k(cb['differentiating_cost'])}",
       f"- one connection, linear grid price ({lin:.2f} CAD/kW-yr above 600 kW): "
       f"{k(a_shared_lin)}",
       f"- demand charges change by {k(cb['shared_depot_demand_cost'] - cb['separate_depot_demand_cost'], 3)}: "
       "route peaks coincide, so one meter bills the same peak",
       f"- coordinated cases with the depot upgrade priced linearly on the realised peak: "
       f"B {k(depot_lin(B))}, C {k(depot_lin(C))}, D (v9rev) {k(depot_lin(D9))}",
       f"- saving on this common basis (one connection, linear): incumbent "
       f"{k(a_shared_lin - depot_lin(C))} ({100 * (a_shared_lin - depot_lin(C)) / a_shared_lin:.1f}%), "
       f"certified at least {k(a_lb_shared_lin - depot_lin(C))}",
       "- depot peak of the coordinated cases (4,600 kW) equals existing 600 kW + the "
       "4 MW tier exactly: the peak is set by the tier, so the 1.6 MW peak "
       "reduction is a tier outcome and uncertified. Terminal grid tiers are "
       "kept as solved (terminal peaks are not archived).", ""]
out["division"] = {"A": {"ub": a_ub, "lb": a_lb, "parts": a_parts,
                         "shared_linear": a_shared_lin},
                   "B": B, "C": {x: C[x] for x in ("obj_solver", "lb_solver", "n_ffh",
                                                    "cost_parts", "peak_depot_kW")},
                   "D_v10": D, "coord_interval": [coord_lb, coord_ub]}

# hand-written diagnostic note (section 5), kept across re-runs
_note = os.path.join(V10, "diagnostic_assignment.md")
if os.path.exists(_note):
    md += ["", open(_note).read().rstrip()]
open(os.path.join(V10, "RESULTS_v10.md"), "w").write("\n".join(md) + "\n")
json.dump(out, open(os.path.join(V10, "results_v10.json"), "w"), indent=1, default=str)
print("\n".join(md))
