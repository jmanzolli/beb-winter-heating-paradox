def load(fn):
    return json.load(open(fn)) if os.path.exists(fn) else None



def _m2_variant(body):
    """Long-format (main_2, single-column elsarticle) copy of a table.
    Tables that are full-width (table*) in the two-column IEEE layout and have
    seven or more columns go on a landscape page (sidewaystable); the others
    become one-column tables. The tabular is capped at the available width
    with adjustbox, which never scales a table up. IEEE-style section numbers
    in notes are mapped to main_2 labels."""
    import re as _re
    ncol = 0
    k = body.find("\\begin{tabular}{")
    if k >= 0:
        k += len("\\begin{tabular}{")
        depth, spec = 1, ""
        while k < len(body) and depth:
            ch = body[k]
            depth += (ch == "{") - (ch == "}")
            if depth == 1 and ch not in "{}":
                spec += ch
            k += 1
        ncol = sum(spec.count(c) for c in "lrcpX")
    wide = "\\begin{table*}" in body and ncol >= 7
    env = "sidewaystable" if wide else "table"
    b = _re.sub(r"\\begin\{table\*?\}(\[[^\]]*\])?", "\\\\begin{" + env + "}", body)
    b = _re.sub(r"\\end\{table\*?\}", "\\\\end{" + env + "}", b)
    b = _re.sub(r"\\begin\{tabular\}", r"\\begin{adjustbox}{max width=\\textwidth}\\begin{tabular}", b, count=1)
    i = b.rfind("\\end{tabular}")
    if i >= 0:
        b = b[:i] + "\\end{tabular}\\end{adjustbox}" + b[i + len("\\end{tabular}"):]
    for old, lab in (("Sec.~II-D", "sec:mo"), ("Sec.~IV-C", "sec:reliability")):
        b = b.replace(old, "Section~\\ref{" + lab + "}")
    return b

def write(name, body):
    stamp = ("% GENERATED by make_supp_tables.py -- do not edit by hand.\n")
    for d in [OUT] + TEXDIRS:
        os.makedirs(d, exist_ok=True)
        open(os.path.join(d, name), "w").write(stamp + body)
        # review (2026-11-07): width-capped copy for the long-format main_2
        if name.endswith(".tex") and "\\begin{tabular" in body:
            open(os.path.join(d, name[:-4] + "_m2.tex"), "w").write(stamp + _m2_variant(body))
    print("wrote", name)


def rev(s):
    """Red revision mark (rev. 2026-09-28); \\rev is defined in the preamble.
    TAB_NO_REV=1 writes the content without the mark."""
    if os.environ.get("TAB_NO_REV"):
        return s
    return r"\rev{%s}" % s


def esc(s):
    return s.replace("_", r"\_")


# ------------------------------------------------------------ sensitivities
def table_sens(runs):
    base = runs.get("policy_lam100")
    pat = re.compile(r"^(ffh_om_|ffh_capex_|grid_|batt_|derate_|reserve_|"
                     r"spare_|precond_tau_|frozen_z|n_minus_1)")
    sel = sorted(l for l in runs if pat.match(l))
    if not sel or not base:
        print("SKIP tab_sens")
        return
    rows = []
    for l in sel:
        r = runs[l]
        d = (r["F1"] - base["F1"]) / 1e3
        fleet = ", ".join(f"{v}$\\times$" + k.replace("NF-", "")
                          for k, v in sorted(r["fleet"].items()))
        rows.append(f"{esc(l)} & {r['F1']/1e3:,.1f} & {d:+.1f} & "
                    f"{r['abs_gap']:,.0f} & {r['co2_t']:.2f} & "
                    f"{r['diesel_L']:,.0f} & {fleet} \\\\")
    body = r"""\begin{table}[!ht]
\caption{Route~52 sensitivity runs, with $\Delta F_1$ relative to the
$\lambda=100$~CAD/t\COtwo{} solution.}
\label{tab:supp-sens}
\centering
\footnotesize
\setlength{\tabcolsep}{4pt}
\begin{tabular}{@{}lrrrrrl@{}}
\toprule
\textbf{Run} & \textbf{$F_1$ (kCAD/yr)} & \textbf{$\Delta F_1$} &
\textbf{Gap (CAD)} & \textbf{\COtwo{} (t/yr)} & \textbf{Diesel (L)} &
\textbf{Fleet} \\
\midrule
%s
\bottomrule
\end{tabular}
\end{table}
""" % "\n".join(rows)
    write("tab_sens.tex", body)


