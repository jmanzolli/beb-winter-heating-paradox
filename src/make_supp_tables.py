        dev = 100.0 * (r["diesel_L"] - obs) / obs
        rows.append(f"{r['n']}$\\times${r['kW']} & {r['installed_kW']:,} & "
                    f"{r['diesel_L']:,.0f} & {dev:+.1f} & {r['F1']/1e3:,.1f} \\\\")
