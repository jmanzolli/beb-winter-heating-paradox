"""Reliability table for main_2 (protocol v10), from v10rev/results_v10.json.

Writes ../overleaf-git/supp_tables/tab_rel_v10_m2.tex. No solver.
Run from code/: python3 make_tab_rel_v10.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
R = json.load(open(os.path.join(HERE, "v10rev", "results_v10.json")))
REL, EV = R["reliability"], R["evals"]
arc = {r["label"]: r for r in json.load(open(os.path.join(
    HERE, "server_v10", "campaign_v9rev_results.json")))["runs"]}
rm = {r["label"]: r for r in json.load(open(os.path.join(
    HERE, "server_v10", "relmatch_v9.json")))["runs"]}
d0 = arc["econ_lam0"]["F1"]
# cost over D0 (kCAD/yr); the design-day design by the fixed-design evaluation
ROWS = [("econ_lam0", "D0, 18 heaters", 0.0),
        ("eps_0.00", "D4, heater-free", (arc["eps_0.00"]["F1"] - d0) / 1e3),
        ("relmatch_eps0_r25", "Heater-free, 25~kWh reserve",
         (rm["relmatch_eps0_r25"]["F1"] - d0) / 1e3),
        ("relmatch_eps0_r100#h", "Heater-free, 100~kWh reserve",
         (rm["relmatch_eps0_r100"]["F1"] - d0) / 1e3),
        ("det_designday#h", "Design-day, 3 heaters",
         (EV["det_designday_eval"]["F1"] - EV["econ_lam0_eval"]["F1"]) / 1e3)]


def cells(d, lv):
    x = REL[f"{d}|{lv}"]
    w, s = x["winter_weighted"], x["severe"]
    h = w["historical_24_winters"]
    return (f"{w['reserve_breach_days_per_winter']:.2f} ({h['reserve_breach_days']['max']:.2f})",
            f"{w['trips_lost_per_winter']:.2f} ({h['trips_lost']['max']:.2f})",
            f"{100 * s['p_reserve_compliant']:.1f}", f"{100 * s['p_trips_completed']:.1f}",
            f"{100 * s['p_comfort_met']:.1f}")


L = [r"% GENERATED by make_tab_rel_v10.py from v10rev/results_v10.json. Do not edit by hand.",
     r"\begin{table*}[pos=tp]",
     r"\caption{Out-of-sample outcomes of the Route~52 designs, 1{,}000 sampled days per band. "
     r"Per winter of 151 days and 41{,}676 trips: days on which a bus falls below the "
     r"state-of-charge floor or the end-of-day reserve, and trips lost below a 5\% "
     r"state-of-charge cut-off, with the coldest winter of the record (2013--14) in "
     r"parentheses. Severe band: share of days above the reserve, with every trip completed, "
     r"and with cabin heat delivered in full. Cost is relative to design~D0.}",
     r"\label{tab:rel}", r"\centering", r"\small", r"\setlength{\tabcolsep}{4pt}",
     r"\fittab{llrrrrrr@{}}{", r"\toprule",
     r" & & & \multicolumn{2}{c}{\textbf{Per winter}} & \multicolumn{3}{c}{\textbf{Severe band (\% of days)}} \\",
     r"\cmidrule(lr){4-5}\cmidrule(l){6-8}",
     r"\textbf{Heat variation} & \textbf{Design} & \textbf{\makecell{Cost\\(kCAD/yr)}} & "
     r"\textbf{\makecell{Days below\\reserve}} & \textbf{Trips lost} & "
     r"\textbf{\makecell{Above\\reserve}} & \textbf{\makecell{All trips\\completed}} & "
     r"\textbf{\makecell{Heat\\delivered}} \\", r"\midrule"]
for lv, name in (("data", "Data-implied"), ("cv0.20", r"20\% (stress)")):
    for i, (d, dn, c) in enumerate(ROWS):
        L.append(f"{name if i == 0 else ''} & {dn} & {c:+.1f} & " + " & ".join(cells(d, lv)) + r" \\")
    if lv == "data":
        L.append(r"\addlinespace")
L += [r"\bottomrule", "}", r"\end{table*}"]
out = os.path.join(HERE, "..", "overleaf-git", "supp_tables", "tab_rel_v10_m2.tex")
open(out, "w").write("\n".join(L).replace("+0.0", "0.0") + "\n")
print("\n".join(L))
