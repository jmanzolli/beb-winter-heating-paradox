"""
Route 52 prototype v6 — two-stage stochastic MILP for winter-resilient BEB
planning and operation (Paper 2, revision-protocol formulation).

v6 changes (audit of the v5 formulation, REVISION_AUDIT.md Section 3):
  C1  depot preconditioning power is bounded by the ELECTRIC HEATER rating,
      not only by charging acceptance and charger rating. The v5 model let
      up to 40 kW pass through a 23 kW heater in one 0.25 h step; the bound
      was active at the v5 optimum (test_ppre_rating.py), so every v5 run
      was re-solved.
  C2  preconditioning heat credit carries a thermal-retention coefficient
      chi_{b,t} = exp(-(t_dep - t)/tau), tau = PRECOND_TAU_H (0.5 h default,
      swept for sensitivity). Delivered plug energy and credited cabin heat
      are now separate quantities; chi <= 1 makes the credit conservative
      relative to v5, which credited preconditioning at chi = 1.
  C3  one plug per bus per step across ALL sites, charging and
      preconditioning combined (was structurally true, now structural).
  C4  ffh_free flag: FFH-free PROCUREMENT (x_kappa = 0 for FFH classes), as
      distinct from the zero-emissions cap, which only forbids FFH operation.
  C5  preconditioning diagnostics exposed for the run records.

v5 changes (T-ITS revision protocol):
  R1  heater rated-output limits: q_el <= dur * 23 kW (telemetry p99),
      q_ffh <= dur * 12 kW * z_ffh (Paper 1 winter-conditions output)
  R2  off-season scenario (214 days @ ECCC Apr-Oct mean, zero cabin heat):
      scenario weights sum to 365; objective is a true annual cost
  R3  billing-period demand charges: winter peak x 5 months + off-season
      peak x 7 months (conservative representative-day in each period)
  R4  explicit charging/preconditioning plug-exclusivity guard u + upre <= 1
      (windows are disjoint by construction; guard makes it structural)
  R5  optional spare ratio, fixed fleet total, and differentiating-cost
      objective (division-scale certification)
  R6  emissions expression exposed for lexicographic eps-constraint phase 2

v3 = v2 model (all audit fixes) + REAL DATA via route52_inputs.json
(generated by fit_inputs.py from the heating_system_study repo + ECCC):
  - traction interface fitted on 13,757 TTC telemetry runs (drivetrain only)
  - Route 52 blocks built from GTFS-derived branch data (52A/52D/52G,
    Lawrence Stn <-> Pearson / Victory-McNaughton / Martin Grove), 18 blocks
  - 5 temperature bands with ECCC Toronto City day counts (2 winters)
  - grid tiers at 200 $/kW (NREL/industry range); FFH O&M 1,000 $/yr (assumption)

Audit fixes retained from v2: #1 overnight cyclic closure, #2 arrival-SoC
reserve, #3 explicit priced preconditioning, #4 monthly billing peaks,
#5 single annual weights, #6 carbon $/t conversion, #9 one charger class per
site, #10 class-dependent traction, #11 bounded phi, #12 nominal-capacity
convention, #17 asset CRFs + tiered grid upgrades.

Usage:  python3 route52_prototype.py [--sweep N]
"""

